"""Generate C# from the design sheets: one class per sheet, one static instance per row.

usage: py -I tools/gen_sheets.py <namespace> <out.cs> [sheet ...]
Columns whose cells are all numbers become double; everything else is string.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in s.replace("-", "_").split("_") if p)


def lit(v, kind):
    if kind == "double":
        return repr(float(v))
    return json.dumps(str(v), ensure_ascii=False)


def main():
    ns, out, *only = sys.argv[1:]
    lines = ["// <auto-generated> by tools/gen_sheets.py from sheets/*.json. Edit the sheets, not this file. </auto-generated>",
             "#pragma warning disable", f"namespace {ns}", "{"]
    for f in sorted((ROOT / "sheets").glob("*.json")):
        s = json.loads(f.read_text(encoding="utf-8"))
        if only and s["sheet"] not in only:
            continue
        cls = pascal(s["sheet"]) + "Row"
        kinds = {c: "double" if all(isinstance(r.get(c), (int, float)) for r in s["rows"]) else "string" for c in s["columns"]}
        lines.append(f"    /// <summary>{s['about']}</summary>".replace("&", "and").replace("<", "(").replace(">", ")"))
        lines.append(f"    public sealed class {cls}")
        lines.append("    {")
        for c in s["columns"]:
            lines.append(f"        public {kinds[c]} {pascal(c)};")
        for r in s["rows"]:
            init = ", ".join(f"{pascal(c)} = {lit(r[c], kinds[c])}" for c in s["columns"])
            lines.append(f"        public static readonly {cls} {pascal(r['id'])} = new {cls} {{ {init} }};")
        lines.append(f"        public static readonly {cls}[] All = {{ {', '.join(pascal(r['id']) for r in s['rows'])} }};")
        lines.append("    }")
    lines.append("}")
    pathlib.Path(out).parent.mkdir(parents=True, exist_ok=True)
    pathlib.Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
