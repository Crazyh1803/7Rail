"""Generate the mod's 7 Days XML (kit items, workbench recipes, localization) from the sheets.

usage: py -I tools/gen_xml.py <mod Config dir>
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def sheet(name):
    return json.loads((ROOT / "sheets" / f"{name}.json").read_text(encoding="utf-8"))["rows"]


NAMES = {
    "7railLocomotive": ("EverRail Locomotive", "EverRail's locomotive, running on 7 Days fuel."),
    "7railStorageWagon": ("EverRail Wagon", "EverRail's generic wagon."),
    "7railSolarCarriage": ("EverRail Solar Carriage", "EverRail's Battery Wagon fitted with 7 Days solar cells: charges the train by day."),
    "7railGeneratorCarriage": ("EverRail Generator Carriage", "EverRail's Battery Wagon running EverRail's Iso Generator on 7 Days gas."),
    "7railExpeditionWagon": ("EverRail Expedition Wagon", "EverRail's Expedition Wagon: its side door lets you step off the train to the ground."),
    "7railBatteryWagon": ("EverRail Battery Wagon", "EverRail's Battery Wagon: four more energy cells for the train."),
}
ICONS = {"car_storage_wagon": "cntWoodWritableCrate", "car_solar": "solarbank", "car_generator": "generatorbank", "car_battery": "batterybank", "car_expedition": "cntWoodWritableCrate"}


def main():
    out = pathlib.Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    cars = {c["id"]: c for c in sheet("train_cars")}
    items, recipes, loc = [], [], []
    loc.append("Key,File,Type,UsedInMainMenu,NoTranslate,english")
    for key, (name, desc) in NAMES.items():
        loc.append(f'{key},items,Item,,,"{name}"')
    for r in sheet("recipes"):
        car = cars[r["car"]]
        if car["name_key"] not in NAMES: continue
        name, desc = NAMES[car["name_key"]]
        items.append(f'''  <item name="{r["result_item"]}">
    <property name="Extends" value="resourceMechanicalParts"/>
    <property name="CustomIcon" value="{ICONS[car["id"]]}"/>
    <property name="Stacknumber" value="1"/>
    <property name="Weight" value="40"/>
    <property name="Tags" value="7rail"/>
    <property name="DescriptionKey" value="{r["result_item"]}Desc"/>
  </item>''')
        ingredients = "\n".join(f'    <ingredient name="{i.split(":")[0]}" count="{i.split(":")[1]}"/>' for i in r["ingredients"].split(";"))
        recipes.append(f'''  <recipe name="{r["result_item"]}" count="1" craft_time="60" craft_area="{r["station"]}" tags="workbenchCrafting">
{ingredients}
  </recipe>''')
        loc.append(f'{r["result_item"]},items,Item,,,"{name} kit"')
        loc.append(f'{r["result_item"]}Desc,items,Item,,,"{desc} Hold it and press Use beside the stopped EverRail train to couple it."')
    hdr = "<!-- generated by tools/gen_xml.py from sheets/recipes.json and sheets/train_cars.json -->\n"
    (out / "items.xml").write_text(hdr + '<configs>\n<append xpath="/items">\n' + "\n".join(items) + "\n</append>\n</configs>\n", encoding="utf-8")
    (out / "recipes.xml").write_text(hdr + '<configs>\n<append xpath="/recipes">\n' + "\n".join(recipes) + "\n</append>\n</configs>\n", encoding="utf-8")
    buffs = []
    for b in sheet("buffs"):
        effects = "\n".join(f'      <passive_effect name="{e.split(":")[0]}" operation="{e.split(":")[1]}" value="{e.split(":")[2]}"/>' for e in b["effects"].split(";"))
        buffs.append(f'''  <buff name="{b["buff_name"]}" hidden="true">
    <duration value="{b["duration_s"]}"/>
    <effect_group>
{effects}
    </effect_group>
  </buff>''')
    (out / "buffs.xml").write_text(hdr.replace("recipes.json and sheets/train_cars.json", "buffs.json") + '<configs>\n<append xpath="/buffs">\n' + "\n".join(buffs) + "\n</append>\n</configs>\n", encoding="utf-8")
    (out / "Localization.csv").write_text("\n".join(loc) + "\n", encoding="utf-8")
    print(f"wrote {len(items)} items, {len(recipes)} recipes to {out}")


if __name__ == "__main__":
    main()

